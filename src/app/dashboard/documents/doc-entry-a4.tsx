export type DocEntryField = { label: string; value: string; /** spans both columns — for long text */ full?: boolean };

export type DocEntrySpec = {
  /** The row's id — scopes the shared print CSS (#doc-entry-view-<id>) to this document only. */
  id: string;
  title: string;
  docNo: string;
  date: string;
  /** Issuing company — header line + PrintArea's branding footer. */
  company?: string;
  fields: DocEntryField[];
  total?: { label: string; value: string };
  remark?: string | null;
};

const fmt = (n: number) => n.toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const inr = (n: number) => `₹${fmt(n)}`;
const num = (n: number | null | undefined) => (n == null ? "—" : fmt(n));
const dash = (v: string | number | null | undefined) => (v == null || v === "" ? "—" : String(v));

/** The A4 sheet itself — wrapped in PrintArea so window.print() from the dialog footer prints this document only. */
export function DocEntryA4({ spec }: { spec: DocEntrySpec }) {
  return (
    <PrintArea id={`doc-entry-view-${spec.id}`} companyName={spec.company}>
      <article className="rounded-lg border border-slate-200 bg-white p-6 text-slate-900 print:rounded-none print:border-0 print:p-0">
        <header className="flex items-start justify-between gap-4 border-b-2 border-slate-800 pb-3">
          <div>
            {spec.company && (
              <p className="text-[11px] font-semibold uppercase tracking-wider text-slate-500">{spec.company}</p>
            )}
            <h1 className="text-lg font-bold tracking-wide text-slate-900">{spec.title}</h1>
          </div>
          <div className="text-right text-xs text-slate-500">
            <div className="text-sm font-semibold text-slate-900">{spec.docNo}</div>
            <div>Date: {spec.date}</div>
          </div>
        </header>

        <dl className="mt-4 grid grid-cols-2 gap-x-5 gap-y-3 text-sm">
          {spec.fields.map((f) => (
            <div key={f.label} className={f.full ? "col-span-2" : undefined}>
              <dt className="text-[10px] font-semibold uppercase tracking-wide text-slate-400">{f.label}</dt>
              <dd className="text-slate-800">{f.value}</dd>
            </div>
          ))}
        </dl>

        {spec.total && (
          <div className="mt-5 flex items-center justify-between rounded-lg border border-amber-200 bg-amber-50 px-4 py-3 print:border-slate-300 print:bg-white">
            <span className="text-sm font-semibold text-slate-600">{spec.total.label}</span>
            <span className="text-lg font-bold text-slate-900">{spec.total.value}</span>
          </div>
        )}

        {spec.remark && (
          <p className="mt-4 rounded border border-slate-200 bg-slate-50 px-3 py-2 text-xs leading-relaxed text-slate-600">
            <span className="font-semibold text-slate-700">Remark:</span> {spec.remark}
          </p>
        )}

        <div className="mt-12 flex justify-end">
          <div className="w-52 border-t border-slate-400 pt-1 text-center text-[11px] text-slate-500">
            Authorised Signatory
          </div>
        </div>
      </article>
    </PrintArea>
  );
}

