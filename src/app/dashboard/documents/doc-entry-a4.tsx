// 2026-10-16 — "Document entry me kisi bhi credit note / debit note /
// washing entry / internal invoice / purchase bill / CSB filing ko view
// nahi kar sakte jo A4 dialog box me khulna chahiye tha, print naye page
// par lekar jata hai, edit alag page par lekar jata hai jabki ye sabhi
// same page par dialog box me khulni chahiye":
//
// ONE shared A4 preview document for the 6 flat Document Entry types
// (the tables that have no detail page of their own — only Credit Note /
// Debit Note / Internal Invoice ever had a /report page, and that is
// exactly the navigation the user does not want). The document renders
// straight from the row's own record — no API fetch — so it can never
// fail to open the way an access-checked statement route can, and it
// works for rows not yet sent to Finance (a Purchase Bill with no
// bill_pass_register link still gets a view).
//
// Opened inside the shared A4Dialog (the same dialog Edit already uses —
// see document-entry-tabs.tsx's DocList), printed from the dialog footer
// through the shared PrintArea (A4 @page + "Generated by" footer).
// A4Dialog's own print CSS keeps output to this document only, so
// Print no longer navigates to a separate /report page.
