-- 2026-11-27 — schema_migrations.sequence_no: the migration LEDGER's explicit
-- order (audit fix #3.12).
--
-- WHY
-- The ledger (db/2026-11-26-schema-migrations-ledger.sql) stores one row per
-- applied db/*.sql file, keyed by file name. "Which order do these run in?" was
-- therefore only ever implied by sorting the names — and the oldest files break
-- that: `20260805fixrlsblockinglogin.sql` and its siblings carry a compact
-- `YYYYMMDD` prefix, which sorts AFTER every `YYYY-MM-DD-…` file because "-"
-- sorts before a digit. The admin page's "run these in the order shown" list
-- was therefore wrong for exactly the files nobody remembers.
--
-- THE FIX
-- sequence_no is the file's 1-based position in the committed manifest
-- (src/lib/migrations/manifest.ts, generated by `npm run migrations:manifest`),
-- which sorts by parsed DATE first, then the optional a/b/c letter, then the
-- rest of the name — so the compact legacy names land in their real dates.
-- The admin page orders by this column, and the "Record verified files" action
-- fills it from the manifest at insert time.
--
-- NULLABILITY
-- Nullable on purpose: a row recorded before this column existed has no
-- trustworthy position, and inventing one from a name sort would repeat the
-- very bug this fixes. Those rows sort last, by file name, and the reader keeps
-- working.
--
-- SAFETY
-- Additive only (one nullable column + a comment). Idempotent: safe to run
-- twice. MUST run AFTER db/2026-11-26-schema-migrations-ledger.sql — there is
-- nothing to alter until the ledger table exists.
begin;

alter table schema_migrations
  add column if not exists sequence_no integer;

comment on column schema_migrations.sequence_no is
  '2026-11-27: 1-based position of this file in src/lib/migrations/manifest.ts — the order the one-time patches are meant to be run in (parsed date, then a/b/c letter, then name). NULL on rows recorded before this column existed; those sort last by file name.';

commit;
